// =============================================================================
// CLAIMS AUDIT  (F9): lists every promise, number, client story and testimonial on
// the site, with the proof that is needed before it is published.
//   npm run claims            -> writes docs/content-audit.md
// The owner reads that file, and for each line decides: Keep, Change, Remove, or
// "Label as concept". Nothing here is invented: every row is a real sentence from
// src/content/en (French and Arabic say the same thing).
// =============================================================================
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(root, "..", "..");
const contentDir = path.join(root, "src", "content", "en");

function* walk(value, trail = "") {
  if (typeof value === "string") yield [trail, value];
  else if (Array.isArray(value)) for (const [i, v] of value.entries()) yield* walk(v, `${trail}[${i}]`);
  else if (value && typeof value === "object") for (const [k, v] of Object.entries(value)) yield* walk(v, trail ? `${trail}.${k}` : k);
}

// Each rule: what makes a sentence a "claim", and what proof it needs.
const RULES = [
  { type: "Time promise", test: /\b(\d+ ?(to|-) ?\d+|\d+) ?(h|hours?|days?|weeks?|minutes?|min)\b|24\/7|within (a few )?hours|in minutes/i, proof: "Can the team really keep this deadline every time? Write the real timing you can guarantee.", action: "Confirm or soften" },
  { type: "Free or no-cost offer", test: /\bfree\b|no payment|no obligation|owe nothing|at no cost|without paying/i, proof: "Confirm the business can afford it and what exactly is included (rounds of changes, formats). The Terms page must say the same.", action: "Confirm" },
  { type: "Money and payment terms", test: /\b\d{1,3} ?%|\bMAD\b|payment|pay\b|quote|deposit/i, proof: "Must match the real contract and the Terms page (30 / 30 / 40 schedule).", action: "Confirm" },
  { type: "Result or statistic", test: /[×x]\d|\b\d+ ?%|\b\d{2,3}\b ?(\/|score|speed)|uptime|99\.9|\b\d+(\.\d+)? ?(s|seconds)\b/i, proof: "A measurement with a date and a tool (Lighthouse, Analytics, client report). Without proof it is a claim that can be challenged.", action: "Prove or label as concept" },
  { type: "Absolute word", test: /\b(never|always|guarantee|every|all of|zero|no one|nobody)\b/i, proof: "Absolute promises are risky. Keep only if it is literally true.", action: "Confirm or soften" },
  { type: "Experience or size of the team", test: /\b(team|engineers?|designers?|experts?|years?|full-stack|agency)\b/i, proof: "Public wording is \"an agency with a team\" (decision). No names or photos on the site. Make sure the team claim is true.", action: "Confirm" },
  { type: "Location and hours", test: /Tangier|Morocco|Mon(day)? to|09:00|18:00|Saturday|hours/i, proof: "Real city, real opening hours, same as Google Business Profile.", action: "Confirm" },
  { type: "Legal or data statement", test: /law 09-08|CNDP|cookies?|personal data|analytics|tracking|delete your data|12 months|30 days/i, proof: "Must be true in practice and reviewed by a lawyer.", action: "Lawyer review" },
];

const lines = [];
const add = (s = "") => lines.push(s);

add("# Content audit: claims, numbers, case studies and testimonials");
add("");
add(`Generated by \`npm run claims\` on ${new Date().toISOString().slice(0, 10)} from \`apps/web/src/content/en\`. French and Arabic carry the same claims.`);
add("");
add("**How to use:** read each table, then write your decision in the last column (Keep, Change to ..., Remove, Label as concept). Send the file back and the text is updated in all three languages.");
add("");

// ---- 1. Case studies and testimonials (the biggest risk) -----------------------
const projects = JSON.parse(readFileSync(path.join(contentDir, "projects.json"), "utf8"));
const workPage = JSON.parse(readFileSync(path.join(contentDir, "work-page.json"), "utf8"));
add("## 1. Case studies and client quotes");
add("");
add(`The Work page itself says: *“${workPage.sampleNote}”*. These four projects were written as **samples** to design the pages. Each one needs one decision.`);
add("");
add("| Project | Client (as written) | Status shown | Results claimed | Quote | Proof needed | Decision |");
add("|---|---|---|---|---|---|---|");
for (const p of projects) {
  const results = p.case.results.map((r) => `${r.value} ${r.label}`).join("; ");
  add(`| ${p.title} | ${p.case.facts.client}, ${p.url || "private"} | ${p.status} | ${results} | “${p.case.quote.text}” (${p.case.quote.by}) | Signed permission of the client to be named; the measurement (tool, date) behind every result; written approval of the quote. | Real / Label as concept / Remove |`);
}
add("");
add("If a project is a **concept** (not a real client), the site must say so. The code already shows the sample note; remove it only when every project above is real.");
add("");

// ---- 2. Claims by type ----------------------------------------------------------
add("## 2. Every promise and number, by type");
add("");
const seen = new Set();
const byType = new Map();
for (const file of readdirSync(contentDir).filter((f) => f.endsWith(".json") && !["seo.json", "nav.json", "not-found.json"].includes(f))) {
  if (file === "projects.json") continue; // covered above
  const json = JSON.parse(readFileSync(path.join(contentDir, file), "utf8"));
  for (const [key, text] of walk(json)) {
    if (text.length < 12 || /^\{\{/.test(text) || /^[#/]/.test(text) || /^https?:/.test(text)) continue;
    if (/(placeholder|label|message|href|icon|id|slug|art|vibe|visual)$/i.test(key.split(".").pop() ?? "")) continue;
    for (const rule of RULES) {
      if (!rule.test.test(text)) continue;
      const id = `${rule.type}|${text}`;
      if (seen.has(id)) continue;
      seen.add(id);
      if (!byType.has(rule.type)) byType.set(rule.type, { rule, rows: [] });
      byType.get(rule.type).rows.push({ file, key, text });
    }
  }
}
for (const { rule, rows } of byType.values()) {
  add(`### ${rule.type} (${rows.length})`);
  add("");
  add(`**Proof needed:** ${rule.proof}`);
  add("");
  add("| File | Where | Text | Suggested | Decision |");
  add("|---|---|---|---|---|");
  for (const row of rows) add(`| ${row.file.replace(".json", "")} | \`${row.key}\` | ${row.text.replace(/\|/g, "\\|").replace(/\n/g, " ")} | ${rule.action} | |`);
  add("");
}

// ---- 3. Texts that are not translated (decorative mock-ups) --------------------
const mock = [];
function* tsx(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* tsx(full);
    else if (entry.name.endsWith(".tsx")) yield full;
  }
}
for (const file of tsx(path.join(root, "src", "components", "sections"))) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(/>\s*([A-Z][A-Za-z0-9 ·.,’'%:+-]{3,40})\s*</g)) mock.push(`${path.relative(path.join(root, "src"), file).replace(/\\/g, "/")}: "${m[1].trim()}"`);
  for (const m of text.matchAll(/(?:name|stock|tag|label): "([A-Z][A-Za-z0-9 ·.,’'%:+-]{3,40})"/g)) mock.push(`${path.relative(path.join(root, "src"), file).replace(/\\/g, "/")}: "${m[1]}"`);
}
add("## 3. Texts drawn inside the decorative pictures");
add("");
add("The small interface mock-ups (shop, dashboard, booking, blog covers) contain short English words that are **not** translated, so on the French and Arabic sites they stay in English. They are decorative (hidden from screen readers) but visible. Decision needed: leave as is, or ask for them to be moved into the content files and translated.");
add("");
for (const m of [...new Set(mock)].slice(0, 60)) add(`- ${m}`);
add("");

// ---- 4. Business data -----------------------------------------------------------
const site = JSON.parse(readFileSync(path.join(root, "src", "content", "shared", "site.json"), "utf8"));
add("## 4. Business details used everywhere");
add("");
add("Source of truth: `apps/web/src/content/shared/site.json`. The release build refuses to run while one of these is still a placeholder.");
add("");
add("| Field | Current value | Real value |");
add("|---|---|---|");
for (const [k, v] of Object.entries(site)) add(`| ${k} | ${typeof v === "object" ? JSON.stringify(v) : String(v)} | |`);
add("");

mkdirSync(path.join(repoRoot, "docs"), { recursive: true });
const out = path.join(repoRoot, "docs", "content-audit.md");
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`claims audit written: ${path.relative(repoRoot, out)} (${byType.size} claim types, ${projects.length} case studies)`);
